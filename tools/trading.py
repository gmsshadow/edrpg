"""
Advanced Trading price indices (Super Traders Supplement pp.8–14) → module/trading-data.mjs.

tools/price-indices.json holds the seven indices as extracted from the book: {index: [[commodity, [12 prices]], ...]}.
Prices are credits per ton, the same to buy or sell; "-" means not traded at that column (illegal goods only appear in
the black-market columns 3, 7 and 11); bracketed prices are printed that way in the book. Run `python3 tools/trading.py`.
"""
import json, os

HERE = os.path.dirname(__file__)
data = json.load(open(os.path.join(HERE, "price-indices.json"), encoding="utf-8"))
out = ["/** Generated by tools/trading.py from the Super Traders Supplement's price indices. Do not edit. */",
       f"export const PRICE_INDICES = {json.dumps(data, ensure_ascii=False)};", ""]
with open(os.path.join(HERE, "..", "module", "trading-data.mjs"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(out))
print(f"{len(data)} price indices, {len(next(iter(data.values())))} commodities each")
